export type FillToken = "none" | "soft" | "medium" | "dark" | "accent";

export interface PartStyle {
  fill?: FillToken;
  dashed?: boolean;
  thick?: boolean;
  opacity?: number;
  /** شعاع گوشه برای مستطیل (نرمال‌شده) */
  r?: number;
}

export type Part =
  | ({ kind: "rect"; x: number; y: number; w: number; h: number; r?: number } & PartStyle)
  | ({ kind: "circle"; cx: number; cy: number; r: number } & PartStyle)
  | ({ kind: "poly"; points: [number, number][]; closed?: boolean } & PartStyle)
  /** خط بر حسب متر نسبت به مرکز شیء (برای نمادهای مقیاس‌واقعی مثل لنگهٔ در) */
  | ({ kind: "mline"; x1: number; y1: number; x2: number; y2: number } & PartStyle)
  /** کمان بر حسب متر نسبت به مرکز شیء؛ زاویه ۰ درجه = شرق، پادساعتگرد */
  | ({ kind: "marc"; cx: number; cy: number; r: number; from: number; to: number } & PartStyle)
  | ({ kind: "line"; x1: number; y1: number; x2: number; y2: number } & PartStyle);

const R = (x: number, y: number, w: number, h: number, style: PartStyle = {}, r = 0): Part => {
  const { r: styleRadius, ...rest } = style;
  return { kind: "rect", x, y, w, h, r: styleRadius ?? r, ...rest };
};
const C = (cx: number, cy: number, r: number, style: PartStyle = {}): Part => ({ kind: "circle", cx, cy, r, ...style });
const P = (points: [number, number][], style: PartStyle = {}): Part => ({ kind: "poly", points, ...style });
const L = (x1: number, y1: number, x2: number, y2: number, style: PartStyle = {}): Part => ({
  kind: "line",
  x1,
  y1,
  x2,
  y2,
  ...style,
});
const ML = (x1: number, y1: number, x2: number, y2: number, style: PartStyle = {}): Part => ({
  kind: "mline",
  x1,
  y1,
  x2,
  y2,
  ...style,
});
const MA = (cx: number, cy: number, r: number, from: number, to: number, style: PartStyle = {}): Part => ({
  kind: "marc",
  cx,
  cy,
  r,
  from,
  to,
  ...style,
});

