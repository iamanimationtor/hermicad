export function catalogByCategory(categoryId: string): CatalogItem[] {
  return CATALOG.filter((entry) => entry.category === categoryId);
}

export function searchCatalog(query: string, category?: string): CatalogItem[] {
  const q = query.trim().toLowerCase();
  return CATALOG.filter((entry) => {
    if (category && entry.category !== category) return false;
    if (!q) return true;
    return (
      entry.nameFa.includes(query.trim()) ||
      entry.nameEn.toLowerCase().includes(q) ||
      entry.id.includes(q) ||
      (entry.tags ?? []).some((tag) => tag.toLowerCase().includes(q))
    );
  });
}
